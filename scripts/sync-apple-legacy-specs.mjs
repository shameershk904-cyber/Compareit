function applyUpdate(phoneObj, update) {
  const next = { ...phoneObj };
  if (update.model) next.model = update.model;
  if (update.display) next.display = { ...phoneObj.display, ...update.display };
  if (update.platform) next.platform = { ...phoneObj.platform, ...update.platform };
  if (update.memory) next.memory = { ...phoneObj.memory, ...update.memory };
  if (update.battery) next.battery = { ...phoneObj.battery, ...update.battery };
  if (update.camera) next.camera = { ...phoneObj.camera, ...update.camera };
  if (update.connectivity) next.connectivity = { ...phoneObj.connectivity, ...update.connectivity };
  if (update.detailed_specs) next.detailed_specs = update.detailed_specs;
  next.specs_source = update.source;
  return next;
}

