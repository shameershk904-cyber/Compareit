/**
 * Sync older / discontinued Apple iPhone specs from support.apple.com into phones.json.
 *
 * Usage: node scripts/sync-apple-legacy-specs.mjs
 */
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const JSON_PATH = join(__dirname, "..", "public", "data", "phones.json");

function item(label, value) {
  return { label, value };
}

function ds(o) {
  const fiveG = o.fiveG ?? false;
  const nfc = o.nfc ?? true;
  return {
    Build: [
      item("OS", o.os),
      item("UI", "iOS"),
      item("Dimensions", o.dimensions),
      item("Weight", o.weight),
      item("SIM", o.sim),
      item("Colors", o.colors),
    ],
    Frequency: [
      item("2G Band", o.band2g || "GSM 850 / 900 / 1800 / 1900"),
      item("3G Band", o.band3g || "UMTS/HSPA+ 850 / 900 / 1700/2100 / 1900 / 2100"),
      item("4G Band", o.band4g || (o.lte ? "LTE (model-dependent bands)" : "No")),
      item("5G Band", fiveG ? "5G (sub-6 / mmWave where supported)" : "No"),
    ],
    Processor: [
      item("CPU", o.cpu),
      item("Chipset", o.chipset),
      item("GPU", o.gpu),
    ],
    Display: [
      item("Technology", o.displayTech),
      item("Size", o.displaySize),
      item("Resolution", o.displayRes),
      item("Protection", o.protection),
      item("Extra Features", o.displayExtra),
    ],
    Memory: [
      item("Built-in", `${o.storage}GB Built-in, ${o.ram}GB RAM`),
      item("Card", "No"),
    ],
    Camera: [
      item("Main", o.cameraMain),
      item("Features", o.cameraFeatures),
      item("Front", o.cameraFront),
    ],
    Connectivity: [
      item("WLAN", o.wlan),
      item("Bluetooth", o.bluetooth),
      item("GPS", o.gps || "Yes (GPS/GNSS)"),
      item("USB", o.usb),
      item("NFC", nfc ? "Yes" : "No"),
      item(
        "Data",
        fiveG
          ? "GPRS, EDGE, 3G (HSPA), 4G LTE, 5G"
          : o.lte
            ? "GPRS, EDGE, 3G (HSPA), 4G LTE"
            : "GPRS, EDGE, 3G (HSPA)"
      ),
    ],
    Features: [
      item("Sensors", o.sensors),
      item("Audio", o.audio),
      item("Browser", "Safari / HTML5"),
      item("Messaging", "iMessage, SMS (threaded view), MMS, Email, Push Email"),
      item("Games", "Built-in + Downloadable from App Store"),
      item("Torch", o.torch ?? "Yes"),
      item("Extra", o.extras),
    ],
    Battery: [item("Capacity", o.battery)],
  };
}

function phone(partial) {
  const {
    source,
    model,
    display,
    platform,
    memory,
    battery,
    camera,
    connectivity,
    detailed,
  } = partial;
  return {
    source,
    model,
    display,
    platform,
    memory,
    battery,
    camera,
    connectivity,
    detailed_specs: ds(detailed),
  };
}

